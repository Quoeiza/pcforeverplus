-- MostlyNotBroken roads (MNBRoads.lua)
-- One copy of this file ships inside every MostlyNotBroken add-on for WoW Forever that points the way
-- (SnuggleUp Forever, ProfitCrafter Forever, ...). The newest copy loaded takes over; older ones step aside.
--
-- Waypoints along the roads and paths drawn on each zone's map, where roads bend and meet. An arrow that
-- asks MostlyNotBrokenRoads:Aim follows the roads round mountains and through towns instead of a straight
-- line over them. Off the roads, the add-on falls back to walked ground (MNB.lua) or a straight line.
--
-- For add-ons (on the global MostlyNotBrokenRoads; world positions as C_Map.GetWorldPosFromMapPos gives):
--   R:Aim(c, wx, wy, tx, ty)    where to head (world x, y) from (wx, wy) to (tx, ty) on continent c, whether
--                                you're on the road, and the next junction (world x, y). nil = no road helps.
--   R.junctions                 { c = continent, list = { { x, y }, ... } }: every junction still ahead
--                                (after the last Aim), for stars on the world map
--   R:Way(c, wx, wy, tx, ty)    the whole way by road: { { x, y, isJunction }, ... }
--   R.DATA[map]                 the roads: { { x, y, x, y, ... }, ... } in map coordinates (0-100)

local MINOR = 2
local Roads = _G.MostlyNotBrokenRoads
if Roads and (Roads.MINOR or 0) >= MINOR then return end -- the same or a newer copy is already running
Roads = { nets = {}, MINOR = MINOR }
_G.MostlyNotBrokenRoads = Roads

local function World(map, x, y)
    if not (C_Map and C_Map.GetWorldPosFromMapPos and CreateVector2D) then return nil end
    local ok, cont, pos = pcall(C_Map.GetWorldPosFromMapPos, map, CreateVector2D(x, y))
    if not ok or not cont or not pos then return nil end
    local wx, wy = pos.x, pos.y
    if (wx == nil or wy == nil) and pos.GetXY then wx, wy = pos:GetXY() end
    if not wx or not wy then return nil end
    return cont, wx, wy
end

Roads.OFF = 3.0          -- a yard off the road counts as this many on it: stay on the road unless it is far round
Roads.ON_YD = 35         -- this close to a road: you're on it
Roads.REACH_YD = 30      -- a waypoint this close is reached: on to the next one
Roads.JOIN_YD = 20       -- points this close are one waypoint
Roads.END_YD = 60        -- a road's loose end this close to another road joins it (a junction drawn a bit apart)
Roads.EDGE_YD = 400      -- a road's loose end at a zone's edge joins the next zone's road this close
Roads.RAMP_YD = 900      -- roads are joined and left only within this of you and of the stop
Roads.CACHE_YD = 8       -- worked out again after moving this far (or after half a second)
local CELL = 100         -- yards: the spatial grid used to find nearby waypoints quickly

local function Dist(ax, ay, bx, by) return math.sqrt((ax - bx) ^ 2 + (ay - by) ^ 2) end

-- the nearest spot on the segment a-b to p, and how far it is
local function OnSegment(px, py, ax, ay, bx, by)
    local dx, dy = bx - ax, by - ay
    local len2 = dx * dx + dy * dy
    local t = len2 > 0 and math.max(0, math.min(1, ((px - ax) * dx + (py - ay) * dy) / len2)) or 0
    local qx, qy = ax + dx * t, ay + dy * t
    return qx, qy, Dist(px, py, qx, qy)
end

local function Key(cx, cy) return cx * 100000 + cy end

-- waypoints within r yards of (x, y): calls fn(i, d)
local function Near(n, x, y, r, fn)
    local c0x, c0y = math.floor((x - r) / CELL), math.floor((y - r) / CELL)
    local c1x, c1y = math.floor((x + r) / CELL), math.floor((y + r) / CELL)
    for cx = c0x, c1x do
        for cy = c0y, c1y do
            local list = n.grid[Key(cx, cy)]
            if list then
                for _, i in ipairs(list) do
                    local p = n.nodes[i]
                    local d = Dist(x, y, p[1], p[2])
                    if d <= r then fn(i, d) end
                end
            end
        end
    end
end

local function Link(n, a, b)
    if a == b then return end
    for _, e in ipairs(n.adj[a]) do if e[1] == b then return end end
    local pa, pb = n.nodes[a], n.nodes[b]
    local len = Dist(pa[1], pa[2], pb[1], pb[2])
    table.insert(n.adj[a], { b, len })
    table.insert(n.adj[b], { a, len })
    n.edges[#n.edges + 1] = { a, b }
end

-- every road in the world, per continent: waypoints { x, y, map } (world yards) and the roads between them
function Roads:Build()
    if self.built then return end
    local nets = {}
    local function net(c)
        nets[c] = nets[c] or { nodes = {}, adj = {}, edges = {}, grid = {} }
        return nets[c]
    end
    local function node(n, x, y, map)
        local found, best
        Near(n, x, y, self.JOIN_YD, function(i, d) if not best or d < best then found, best = i, d end end)
        if found then return found end
        n.nodes[#n.nodes + 1] = { x, y, map }
        local i = #n.nodes
        n.adj[i] = {}
        local k = Key(math.floor(x / CELL), math.floor(y / CELL))
        n.grid[k] = n.grid[k] or {}
        table.insert(n.grid[k], i)
        return i
    end
    local any = false
    for map, lines in pairs(self.DATA) do
        for _, line in ipairs(lines) do
            local last, lastNet
            for k = 1, #line - 1, 2 do
                local c, wx, wy = World(map, line[k] / 100, line[k + 1] / 100)
                if c then
                    any = true
                    local n = net(c)
                    local i = node(n, wx, wy, map)
                    if last and lastNet == n then Link(n, last, i) end
                    last, lastNet = i, n
                else
                    last = nil
                end
            end
        end
    end
    if not any then return end -- the map isn't ready yet: try again later
    -- loose ends: join the nearest other road (a junction drawn a little apart), or at a zone's edge the
    -- next zone's road
    for _, n in pairs(nets) do
        local count = #n.nodes
        for i = 1, count do
            if #n.adj[i] <= 1 then
                local p = n.nodes[i]
                local nb = n.adj[i][1] and n.adj[i][1][1]
                local bestSame, dSame, bestOther, dOther
                Near(n, p[1], p[2], self.EDGE_YD, function(j, d)
                    if j ~= i and j ~= nb then
                        if n.nodes[j][3] == p[3] then
                            if d <= self.END_YD and (not dSame or d < dSame) then bestSame, dSame = j, d end
                        elseif not dOther or d < dOther then
                            bestOther, dOther = j, d
                        end
                    end
                end)
                if bestSame then Link(n, i, bestSame) end
                if bestOther then Link(n, i, bestOther) end
            end
        end
    end
    -- junctions: where roads meet (three ways or more), where a road ends, and at a zone's edge. The
    -- other waypoints only bend the arrow along the road's curves; the star goes on junctions only.
    for _, n in pairs(nets) do
        n.junction = {}
        for i, p in ipairs(n.nodes) do
            local deg, edge = #n.adj[i], false
            for _, e in ipairs(n.adj[i]) do if n.nodes[e[1]][3] ~= p[3] then edge = true end end
            n.junction[i] = deg ~= 2 or edge
        end
    end
    self.nets, self.built = nets, true
end

-- the nearest spot on any road within r: x, y, yards away, and the two waypoints either side of it
local function Nearest(n, px, py, r)
    local best, bx, by, ba, bb
    local seen = {}
    Near(n, px, py, r, function(i)
        for _, e in ipairs(n.adj[i]) do
            local j = e[1]
            local k = i < j and (i * 1000000 + j) or (j * 1000000 + i)
            if not seen[k] then
                seen[k] = true
                local a, b = n.nodes[i], n.nodes[j]
                local qx, qy, d = OnSegment(px, py, a[1], a[2], b[1], b[2])
                if not best or d < best then best, bx, by, ba, bb = d, qx, qy, i, j end
            end
        end
    end)
    return bx, by, best, ba, bb
end

-- a small binary heap for the search
local function Push(h, k, v)
    local n = #h + 1
    h[n] = { k, v }
    while n > 1 do
        local p = math.floor(n / 2)
        if h[p][1] <= h[n][1] then break end
        h[p], h[n] = h[n], h[p]
        n = p
    end
end
local function Pop(h)
    local top = h[1]
    if not top then return nil end
    local last = table.remove(h)
    if #h > 0 then
        h[1] = last
        local i = 1
        while true do
            local a, b, m = i * 2, i * 2 + 1, i
            if h[a] and h[a][1] < h[m][1] then m = a end
            if h[b] and h[b][1] < h[m][1] then m = b end
            if m == i then break end
            h[i], h[m] = h[m], h[i]
            i = m
        end
    end
    return top[2], top[1]
end

-- The way by road from (wx, wy) to (tx, ty) on continent c: a list of { x, y } spots, the first one where
-- you get on the road, and how far you are from the road now. nil = no road helps.
function Roads:Way(c, wx, wy, tx, ty)
    self:Build()
    local n = self.nets[c]
    if not n or #n.edges == 0 then return nil end
    local OFF, RAMP = self.OFF, self.RAMP_YD
    local N = #n.nodes
    local S, T, P, Q = N + 1, N + 2, N + 3, N + 4
    local pos = setmetatable({ [S] = { wx, wy }, [T] = { tx, ty } }, { __index = n.nodes })
    local extra = { [S] = {}, [P] = {}, [Q] = {} }
    local into = {} -- road waypoint -> links to T or Q
    local function addInto(i, v, cost)
        into[i] = into[i] or {}
        table.insert(into[i], { v, cost })
    end
    local direct = Dist(wx, wy, tx, ty)
    table.insert(extra[S], { T, direct * OFF })
    local px, py, pd, pa, pb = Nearest(n, wx, wy, RAMP)
    if px then
        pos[P] = { px, py }
        table.insert(extra[S], { P, pd * OFF })
        table.insert(extra[P], { pa, Dist(px, py, n.nodes[pa][1], n.nodes[pa][2]) })
        table.insert(extra[P], { pb, Dist(px, py, n.nodes[pb][1], n.nodes[pb][2]) })
    end
    Near(n, wx, wy, RAMP, function(i, d) table.insert(extra[S], { i, d * OFF }) end)
    Near(n, tx, ty, RAMP, function(i, d) addInto(i, T, d * OFF) end)
    local qx, qy, qd, qa, qb = Nearest(n, tx, ty, RAMP)
    if qx then
        pos[Q] = { qx, qy }
        addInto(qa, Q, Dist(qx, qy, n.nodes[qa][1], n.nodes[qa][2]))
        addInto(qb, Q, Dist(qx, qy, n.nodes[qb][1], n.nodes[qb][2]))
        table.insert(extra[Q], { T, qd * OFF })
        if px and ((qa == pa and qb == pb) or (qa == pb and qb == pa)) then
            table.insert(extra[P], { Q, Dist(px, py, qx, qy) })
        end
    end
    -- Dijkstra over the roads, never searching further than going straight would cost
    local limit = direct * OFF
    local dist, prev, done, heap = { [S] = 0 }, {}, {}, {}
    Push(heap, 0, S)
    while true do
        local u, du = Pop(heap)
        if not u then break end
        if u == T then break end
        if not done[u] and du <= limit then
            done[u] = true
            local function relax(v, cost)
                local nd = du + cost
                if not dist[v] or nd < dist[v] then
                    dist[v], prev[v] = nd, u
                    Push(heap, nd, v)
                end
            end
            if u <= N then
                for _, e in ipairs(n.adj[u]) do relax(e[1], e[2]) end
                for _, e in ipairs(into[u] or {}) do relax(e[1], e[2]) end
            else
                for _, e in ipairs(extra[u] or {}) do relax(e[1], e[2]) end
            end
        end
    end
    if not dist[T] then return nil end
    local list, at = {}, T
    while prev[at] do
        table.insert(list, 1, at)
        at = prev[at]
    end
    if #list <= 1 then return nil end -- straight there: no road on the way
    local way = {}
    for _, i in ipairs(list) do
        if i ~= T then way[#way + 1] = { pos[i][1], pos[i][2], i <= N and n.junction[i] or false } end
    end
    return way, pd
end

-- Where to head (world x, y) on the way by road, whether you're on the road now, and the next junction on
-- the way (world x, y; nil when there's none before you leave the road). nil = no road helps.
function Roads:Aim(c, wx, wy, tx, ty)
    local cache = self.cache
    local now = GetTime and GetTime() or 0
    -- (standing still, the way is the same however old it is: worked out again only once you move)
    if not (cache and cache.c == c and cache.tx == tx and cache.ty == ty
        and Dist(cache.wx, cache.wy, wx, wy) < self.CACHE_YD and (now - cache.t < 0.5 or (cache.wx == wx and cache.wy == wy))) then
        local way, onDist = self:Way(c, wx, wy, tx, ty)
        cache = { c = c, wx = wx, wy = wy, tx = tx, ty = ty, t = now, way = way, on = onDist }
        self.cache = cache
    end
    local way = cache.way
    if not way then self.junctions = nil return nil end
    for k, p in ipairs(way) do
        if Dist(wx, wy, p[1], p[2]) > self.REACH_YD then
            local jx, jy
            local list = {}
            for m = k, #way do
                if way[m][3] then
                    if not jx then jx, jy = way[m][1], way[m][2] end
                    list[#list + 1] = { way[m][1], way[m][2] }
                end
            end
            self.junctions = { c = c, list = list } -- every junction still ahead (for the world map)
            return p[1], p[2], (cache.on or math.huge) <= self.ON_YD, jx, jy
        end
    end
    self.junctions = nil
    return nil
end

-- how many waypoints are known
function Roads:Report()
    self:Build()
    local count, zones = 0, 0
    for _, n in pairs(self.nets) do count = count + #n.nodes end
    for _ in pairs(self.DATA) do zones = zones + 1 end
    print(("Roads: %d waypoints in %d zones."):format(count, zones))
end

